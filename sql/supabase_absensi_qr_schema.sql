-- Trigger updated_at
CREATE OR REPLACE FUNCTION absensi_qr.set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 NEW.updated_at = NOW();
 RETURN NEW;
END;
$$;

DO $$
DECLARE t TEXT;
BEGIN
 FOREACH t IN ARRAY ARRAY['users','students','attendance','permission_requests','chatbot_conversations']
 LOOP
  IF EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema='absensi_qr' AND table_name=t AND column_name='updated_at')
     AND NOT EXISTS (SELECT 1 FROM pg_trigger
                     WHERE tgname='trg_'||t||'_updated_at'
                     AND tgrelid=format('absensi_qr.%I',t)::regclass) THEN
   EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON absensi_qr.%I
                   FOR EACH ROW EXECUTE FUNCTION absensi_qr.set_updated_at()',
                  'trg_'||t||'_updated_at',t);
  END IF;
 END LOOP;
END $$;

