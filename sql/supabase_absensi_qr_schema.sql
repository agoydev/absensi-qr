-- ABSENSI SISWA SMK BERBASIS QR CODE
-- Supabase PostgreSQL | Schema: absensi_qr | 31 tabel
-- Aman: tidak menghapus schema/tabel/data yang sudah ada.
-- Catatan: IF NOT EXISTS tidak mengubah struktur tabel yang sudah ada.
CREATE SCHEMA IF NOT EXISTS absensi_qr;

CREATE TABLE IF NOT EXISTS absensi_qr.users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(150) NOT NULL, username VARCHAR(100) UNIQUE NOT NULL,
 email VARCHAR(150) UNIQUE, password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(30) NOT NULL CHECK(role IN ('admin','teacher','student','parent')),
 phone VARCHAR(30), is_active BOOLEAN DEFAULT TRUE,
 created_at TIMESTAMPTZ DEFAULT NOW(), updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS absensi_qr.academic_years (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 year_name VARCHAR(20) NOT NULL UNIQUE, start_date DATE NOT NULL,
 end_date DATE NOT NULL, is_active BOOLEAN DEFAULT FALSE,
 created_at TIMESTAMPTZ DEFAULT NOW(), CHECK(end_date > start_date)
);

CREATE TABLE IF NOT EXISTS absensi_qr.semesters (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 academic_year_id BIGINT NOT NULL REFERENCES absensi_qr.academic_years(id),
 semester_name VARCHAR(20) NOT NULL CHECK(semester_name IN ('Ganjil','Genap')),
 start_date DATE NOT NULL, end_date DATE NOT NULL, is_active BOOLEAN DEFAULT FALSE,
 UNIQUE(academic_year_id, semester_name), CHECK(end_date > start_date)
);

CREATE TABLE IF NOT EXISTS absensi_qr.classes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, grade_level VARCHAR(20) NOT NULL,
 major VARCHAR(100) NOT NULL,
 academic_year_id BIGINT REFERENCES absensi_qr.academic_years(id),
 homeroom_teacher_id BIGINT, is_active BOOLEAN DEFAULT TRUE,
 created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS absensi_qr.teachers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT UNIQUE REFERENCES absensi_qr.users(id) ON DELETE SET NULL,
 teacher_number VARCHAR(50) UNIQUE, name VARCHAR(150) NOT NULL,
 email VARCHAR(150), phone VARCHAR(30), address TEXT,
 is_active BOOLEAN DEFAULT TRUE, created_at TIMESTAMPTZ DEFAULT NOW()
);

DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='fk_classes_homeroom_teacher'
 AND conrelid='absensi_qr.classes'::regclass) THEN
 ALTER TABLE absensi_qr.classes ADD CONSTRAINT fk_classes_homeroom_teacher
 FOREIGN KEY(homeroom_teacher_id) REFERENCES absensi_qr.teachers(id) ON DELETE SET NULL;
 END IF;
END $$;

CREATE TABLE IF NOT EXISTS absensi_qr.parents (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT UNIQUE REFERENCES absensi_qr.users(id) ON DELETE SET NULL,
 name VARCHAR(150) NOT NULL, phone VARCHAR(30) NOT NULL,
 email VARCHAR(150), address TEXT, created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS absensi_qr.students (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 class_id BIGINT REFERENCES absensi_qr.classes(id) ON DELETE SET NULL,
 parent_id BIGINT REFERENCES absensi_qr.parents(id) ON DELETE SET NULL,
 user_id BIGINT UNIQUE REFERENCES absensi_qr.users(id) ON DELETE SET NULL,
 nis VARCHAR(50) NOT NULL UNIQUE, nisn VARCHAR(50) UNIQUE,
 name VARCHAR(150) NOT NULL, gender VARCHAR(20) CHECK(gender IN ('Laki-laki','Perempuan')),
 birth_date DATE, address TEXT, phone VARCHAR(30), photo_url TEXT,
 is_active BOOLEAN DEFAULT TRUE, created_at TIMESTAMPTZ DEFAULT NOW(),
 updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS absensi_qr.subjects (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(50) UNIQUE NOT NULL, name VARCHAR(150) NOT NULL,
 description TEXT, is_active BOOLEAN DEFAULT TRUE, created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS absensi_qr.schedules (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 class_id BIGINT NOT NULL REFERENCES absensi_qr.classes(id),
 subject_id BIGINT NOT NULL REFERENCES absensi_qr.subjects(id),
 teacher_id BIGINT NOT NULL REFERENCES absensi_qr.teachers(id),
 semester_id BIGINT REFERENCES absensi_qr.semesters(id),
 day_of_week SMALLINT NOT NULL CHECK(day_of_week BETWEEN 1 AND 7),
 start_time TIME NOT NULL, end_time TIME NOT NULL,
 late_after_minutes SMALLINT DEFAULT 15, is_active BOOLEAN DEFAULT TRUE,
 created_at TIMESTAMPTZ DEFAULT NOW(), CHECK(end_time > start_time)
);

CREATE TABLE IF NOT EXISTS absensi_qr.sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 schedule_id BIGINT NOT NULL REFERENCES absensi_qr.schedules(id),
 session_date DATE NOT NULL, meeting_number INTEGER NOT NULL,
 start_at TIMESTAMPTZ NOT NULL, end_at TIMESTAMPTZ NOT NULL,
 attendance_deadline TIMESTAMPTZ NOT NULL,
 status VARCHAR(20) DEFAULT 'scheduled'
 CHECK(status IN ('scheduled','ongoing','completed','cancelled')),
 opened_by BIGINT REFERENCES absensi_qr.users(id) ON DELETE SET NULL,
 closed_by BIGINT REFERENCES absensi_qr.users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ DEFAULT NOW(), UNIQUE(schedule_id,session_date),
 CHECK(end_at > start_at)
);

CREATE TABLE IF NOT EXISTS absensi_qr.qr_codes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id BIGINT NOT NULL REFERENCES absensi_qr.students(id) ON DELETE CASCADE,
 qr_token VARCHAR(255) UNIQUE NOT NULL, qr_image_url TEXT,
 generated_at TIMESTAMPTZ DEFAULT NOW(), expired_at TIMESTAMPTZ,
 is_active BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS absensi_qr.attendance (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id BIGINT NOT NULL REFERENCES absensi_qr.sessions(id) ON DELETE CASCADE,
 student_id BIGINT NOT NULL REFERENCES absensi_qr.students(id) ON DELETE CASCADE,
 qr_code_id BIGINT REFERENCES absensi_qr.qr_codes(id) ON DELETE SET NULL,
 attendance_date DATE NOT NULL, attendance_time TIMESTAMPTZ,
 status VARCHAR(30) NOT NULL CHECK(status IN
 ('Hadir','Terlambat','Sakit','Izin','Dispensasi','Tidak Hadir')),
 notes TEXT, recorded_by BIGINT REFERENCES absensi_qr.users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ DEFAULT NOW(), updated_at TIMESTAMPTZ DEFAULT NOW(),
 UNIQUE(session_id,student_id)
);

CREATE TABLE IF NOT EXISTS absensi_qr.permission_requests (
